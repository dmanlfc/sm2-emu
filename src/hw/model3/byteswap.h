// 16- and 32-bit byte swaps (std::byteswap is C++23).
#pragma once

#include "core/types.h"

namespace sm2::hw::model3 {

[[nodiscard]] constexpr u16 bswap(u16 v)
{
    return static_cast<u16>((v >> 8) | (v << 8));
}

[[nodiscard]] constexpr u32 bswap(u32 v)
{
    return (v >> 24) | ((v >> 8) & 0x0000FF00u) | ((v << 8) & 0x00FF0000u) | (v << 24);
}

}  // namespace sm2::hw::model3
